pub const FIRST_EPOCH_JD: f64 = CHIRON_ELEMENTS[0].0;
pub const LAST_EPOCH_JD: f64 = CHIRON_ELEMENTS[CHIRON_ELEMENTS.len() - 1].0;

/// Ob das Datum im Bereich liegt, für den die Tabelle geprüft wurde.
pub fn in_validated_range(jd: f64) -> bool {
    (FIRST_EPOCH_JD - 1000.0..=LAST_EPOCH_JD + 1000.0).contains(&jd)
}

fn nearest_elements(jd: f64) -> &'static Elements {
    let mut best = &CHIRON_ELEMENTS[0];
    for el in CHIRON_ELEMENTS {
        if (el.0 - jd).abs() < (best.0 - jd).abs() {
            best = el;
        }
    }
    best
}

/// Heliozentrische Position (x, y, z) in AU, Ekliptik J2000.
fn heliocentric(jd: f64) -> (f64, f64, f64) {
    let (epoch, e, a, inc, node, arg, ma, n) = *nearest_elements(jd);
    let m = (ma + n * (jd - epoch)).to_radians().rem_euclid(std::f64::consts::TAU);

    let mut ecc_anom = m;
    for _ in 0..60 {
        let delta = (ecc_anom - e * ecc_anom.sin() - m) / (1.0 - e * ecc_anom.cos());
        ecc_anom -= delta;
        if delta.abs() < 1e-13 {
            break;
        }
    }

    let nu = 2.0
        * ((1.0 + e).sqrt() * (ecc_anom / 2.0).sin())
            .atan2((1.0 - e).sqrt() * (ecc_anom / 2.0).cos());
    let r = a * (1.0 - e * ecc_anom.cos());
    let u = nu + arg.to_radians();
    let (i, o) = (inc.to_radians(), node.to_radians());

    (
        r * (o.cos() * u.cos() - o.sin() * u.sin() * i.cos()),
        r * (o.sin() * u.cos() + o.cos() * u.sin() * i.cos()),
        r * u.sin() * i.sin(),
    )
}

/// Geozentrische ekliptikale Länge/Breite/Distanz von Chiron (Äquinoktium des Datums).
fn geocentric(jd_ut: f64) -> Option<(f64, f64, f64)> {
    let sun = sweph::calc(jd_ut, sweph::Body::Sun).ok()?;
    let (x, y, z) = heliocentric(jd_ut);

    // Präzession in Länge: von J2000 auf das Äquinoktium des Datums.
    let t = (jd_ut - 2451545.0) / 36525.0;
    let prec = (5028.796195 * t + 1.1054348 * t * t) / 3600.0;
    let (sp, cp) = prec.to_radians().sin_cos();
    let (xd, yd) = (x * cp - y * sp, x * sp + y * cp);

    let sl = sun.longitude.to_radians();
    let (xg, yg, zg) = (xd + sun.distance * sl.cos(), yd + sun.distance * sl.sin(), z);

    let dist = (xg * xg + yg * yg + zg * zg).sqrt();
    Some((
        yg.atan2(xg).to_degrees().rem_euclid(360.0),
        (zg / dist).asin().to_degrees(),
        dist,
    ))
}

/// (Länge, Breite, Distanz, Geschwindigkeit °/Tag, rückläufig)
pub fn chiron_position(jd_ut: f64) -> Option<(f64, f64, f64, f64, bool)> {
    let (lon, lat, dist) = geocentric(jd_ut)?;
    let before = geocentric(jd_ut - 0.5)?.0;
    let after = geocentric(jd_ut + 0.5)?.0;
    let speed = ((after - before + 540.0).rem_euclid(360.0) - 180.0) / 1.0;
    Some((lon, lat, dist, speed, speed < 0.0))
}
